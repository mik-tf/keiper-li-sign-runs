#!/usr/bin/env python3
"""Generator for the B2 spike data (L = 711): rational zero intervals and sqrt witnesses.

Reads ../code/z2000.json (relative to this directory) (the Arb zero midpoints, sha256 recorded in
cert_comb_711.json) and cert_comb_711.json (weights).  Pure Python integers (no flint).
Usage: python3 -I gen711.py KFIRST KLAST OUTFILE   (0-indexed zeros KFIRST..KLAST-1, k >= 1)
       python3 -I gen711.py --full     (closed-world Python check of all 2000 zeros, prints margins)
"""
import json, sys, math
from fractions import Fraction
from math import isqrt
CODE = "../code/"
S30 = 30                      # grid: gamma_mid = N / 2^30
H = 2 ** 10 + 1               # half-width in units 2^-30: 2^-20 + 2^-31 rounded up
z = json.load(open(CODE + "z2000.json"))
cert = json.load(open(CODE + "cert_comb_711.json"))
A = cert["weights_int_over_2^50"]
M = len(A)
SA = sum(A)

def mid_N(i):
    man, e = z["gamma_mid_man_exp_rad_man_exp"][i][:2]
    f = Fraction(man) * Fraction(2) ** e
    N = round(f * 2 ** S30)
    assert abs(f - Fraction(N, 2 ** S30)) <= Fraction(1, 2 ** 31)
    return N

def theta1(g):   # float, for the chain only
    return 2 * math.atan(1 / (2 * g))

def chain():
    g = mid_N(0) / 2 ** S30
    P = 2 * math.pi / theta1(g)
    xs = [j * P + 0.5 for j in range(M)]
    brk = sorted((1 - (x - math.floor(x)), j) for j, x in enumerate(xs))
    pts = [b for b, _ in brk]
    gaps = [pts[0]] + [pts[i + 1] - pts[i] for i in range(len(pts) - 1)] + [1 - pts[-1]]
    assert min(gaps) > 1e-3, gaps      # P1 radius 6e-6, so jP moves < 5e-5: chain is stable
    vec = [math.floor(x) for x in xs]
    out = [list(vec)]
    for b, j in brk:
        vec[j] += 1
        out.append(list(vec))
    return out, P, min(gaps)

def zero_data(i, v):
    """exact X + iY with 2^50 D^vm B_m = X + iY, witness rho >= 2^40 |B_m|, bound U/2^40."""
    N = mid_N(i)
    Z = (N * N - 2 ** (2 * S30 - 2), N * 2 ** S30)
    D = N * N + 2 ** (2 * S30 - 2)
    vm = max(v)
    X = Y = 0
    for j in range(M):
        pw = (1, 0)
        for _ in range(v[j]):
            pw = (pw[0] * Z[0] - pw[1] * Z[1], pw[0] * Z[1] + pw[1] * Z[0])
        f = A[j] * D ** (vm - v[j])
        X += f * pw[0]; Y += f * pw[1]
    den = 2 ** 50 * D ** vm
    s = isqrt(2 ** 80 * (X * X + Y * Y)) + 1
    rho = -(-s // den)
    assert 2 ** 80 * (X * X + Y * Y) <= rho * rho * den * den
    Elo = (N - H) ** 2 + 2 ** (2 * S30 - 2)
    num = 2 ** 61 * rho * Elo + 2 ** 81 * SA * vm * H
    U = -(-num // (Elo * Elo))
    return N, rho, U


def write_chunk(ci, k0, k1, out):
    vecs, P, gap = chain()
    rows = [[zero_data(i, v) for v in vecs] for i in range(k0, k1)]
    ns = "C%02d" % ci
    with open(out, "w") as f:
        f.write("-- generated by gen711.py --chunk (do not edit). Zeros %d..%d (0-indexed), L = 711, M = 8.\n" % (k0, k1 - 1))
        f.write("import KeiperComb.Numerics711Sound3\nimport KeiperComb.Numerics711Cert\nopen Complex Finset\nnamespace KeiperComb.N711.%s\nopen KeiperComb.N711\n\n" % ns)
        f.write("def nsC : List Nat := %s\n" % [r[0][0] for r in rows])
        for vi in range(len(vecs)):
            f.write("def zerosV%d : List (Nat \u00d7 Nat \u00d7 Nat) := [%s]\n" % (vi, ", ".join("(%d, %d, %d)" % (r[vi][0], r[vi][1], r[vi][2]) for r in rows)))
        f.write("\ndef zsAll : List (List (Nat \u00d7 Nat \u00d7 Nat)) := [%s]\n" % ", ".join("zerosV%d" % vi for vi in range(len(vecs))))
        f.write("def sumU : List Nat := zsAll.map (fun l => (l.map (fun t => t.2.2)).sum)\n\n")
        f.write("theorem ok : checkBatchFast weightsA chainVecs zsAll = true := by decide +kernel\n")
        f.write("theorem ns_eq : zerosV0.map (fun t => t.1) = nsC := by decide +kernel\n\n")
        f.write("""theorem sound : \u2200 col \u2208 transpAux (zsAll.headD []).length zsAll, \u2200 c0 rest, col = c0 :: rest \u2192 Hw \u2264 c0.1 \u2192
    \u2200 q \u2208 chainVecs.zip col, \u2200 \u03b3 : \u211d, ((c0.1 : \u211d) - Hw) / 2 ^ 30 \u2264 \u03b3 \u2192 \u03b3 \u2264 ((c0.1 : \u211d) + Hw) / 2 ^ 30 \u2192
      2 * wOf \u03b3 * \u2016\u2211 j \u2208 range weightsA.length, (((weightsA.getD j 0 : \u211d) / 2 ^ 50 : \u211d) : \u2102) * (qOf \u03b3) ^ (q.1.getD j 0)\u2016
        \u2264 (q.2.2.2 : \u211d) / 2 ^ 40 :=
  checkBatchFast_sound weightsA chainVecs zsAll (by decide +kernel) (by decide +kernel) ok

end KeiperComb.N711.%s
#print axioms KeiperComb.N711.%s.sound
""" % (ns, ns))
    print("wrote", out, "sumU/2^40:", [sum(r[vi][2] for r in rows) / 2**40 for vi in range(len(vecs))][:3], flush=True)

if __name__ == "__main__":
    if sys.argv[1] == "--cert":
        vecs, P, gap = chain()
        open(sys.argv[2], "w").write("-- generated by gen711.py --cert (do not edit)\nnamespace KeiperComb.N711\ndef weightsA : List Nat := %s\ndef chainVecs : List (List Nat) := %s\nend KeiperComb.N711\n" % (A, [[int(x) for x in v] for v in vecs]))
        sys.exit()
    if sys.argv[1] == "--chunk":
        write_chunk(int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), sys.argv[5]); sys.exit()
    vecs, P, gap = chain()
    if sys.argv[1] == "--full":
        import time
        t = time.time()
        tot = [0] * len(vecs)
        for i in range(1, 2000):
            for vi, v in enumerate(vecs):
                tot[vi] += zero_data(i, v)[2]
            if i in (19, 99, 499, 1999 - 1):
                print(i + 1, "zeros done", round(time.time() - t, 1), "s", flush=True)
        print("P1 (float)", P, "min chain gap", gap)
        print("sum_{k>=2} 2 w |B_k| bound per vector (units 2^-40, as float):", [x / 2 ** 40 for x in tot])
        N0 = mid_N(0); Eh = (N0 + H) ** 2 + 2 ** (2 * S30 - 2)
        z1 = 2 * (SA / 2 ** 50) * (2 ** 60 / Eh) * 0.99936
        print("Z1 lower (c0=0.99936):", z1, " W S upper:", cert["W_upper"] * SA / 2 ** 50)
        print("max R per vector:", [(x / 2 ** 40 + cert["W_upper"] * SA / 2 ** 50) / z1 for x in tot])
        sys.exit()
    k0, k1, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
    assert k0 >= 1
    rows = []
    for i in range(k0, k1):
        rows.append([zero_data(i, v) for v in vecs])
    with open(out, "w") as f:
        f.write("-- generated by gen711.py (do not edit). Zeros %d..%d (0-indexed), L = 711, M = 8.\n" % (k0, k1 - 1))
        f.write("import KeiperComb.Numerics711Core\nnamespace KeiperComb.N711\n\n")
        f.write("def weightsA : List Nat := %s\n" % A)
        f.write("def chainVecs : List (List Nat) := %s\n\n" % [[int(x) for x in v] for v in vecs])
        for vi in range(len(vecs)):
            f.write("def zerosV%d : List (Nat × Nat × Nat) := [%s]\n" % (vi, ", ".join("(%d, %d, %d)" % (r[vi][0], r[vi][1], r[vi][2]) for r in rows)))
        f.write("\ndef zsAll : List (List (Nat × Nat × Nat)) := [%s]\n" % ", ".join("zerosV%d" % vi for vi in range(len(vecs))))
        f.write("\nend KeiperComb.N711\n")
        print("wrote", out, "chain", len(vecs), "sumU/2^40 per vec:", [sum(r[vi][2] for r in rows) / 2**40 for vi in range(len(vecs))])
