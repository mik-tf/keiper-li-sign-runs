#!/usr/bin/env python3
"""Generate Challenge.lean (the trusted statement-only file for lake comparator).

Everything is copied verbatim from the solution sources: the definitions the statements mention
(Defs.lean), the grid-ordinate data (the `nsC` lists of the chunk modules, with the same names), and the
statements of the 622 and 711 theorems with the proofs replaced by `sorry`.
Run from this directory: python3 gen_challenge.py > Challenge.lean
"""
import re, sys
K = "KeiperComb/"
def rd(p): return open(K + p, encoding="utf-8").read()

defs = rd("Defs.lean")
def block(src, start, end_marker):
    i = src.index(start); j = src.index(end_marker, i)
    return src[i:j].rstrip() + "\n"
# the five definitions the statements mention, verbatim
d_zero = block(defs, "/-- Nontrivial zeros", "/-- Li's formula, second")
d_li = block(defs, "/-- Li's formula, second", "/-- Li's weight sum")
d_w = block(defs, "/-- Li's weight sum", "/-- The 2000 (here `K`)")
d_zi = block(defs, "/-- The 2000 (here `K`)", "/-- Decidable facts")

out = []
out.append("""import Mathlib

/-!
# Challenge: the statements of Theorem A (runs of Keiper-Li signs), definitions and `sorry` proofs only

This file is the trusted statement file for `lake comparator` (see COMPARATOR.md).  It imports Mathlib
only, not the solution.  Every definition below is copied verbatim from the solution (`Defs.lean`, and the
grid data of the `Numerics*C*.lean` chunk modules, generated by `gen_challenge.py`), because the
comparator requires each constant a statement depends on to be identical in both environments.

The four hypotheses of each theorem are: `RiemannHypothesis`, `LiSecondDiff c`, `LiWeightSum`,
`ZeroIntervals 2000 loQ hiQ` (2000 rational intervals `[(N_k - 1025)/2^30, (N_k + 1025)/2^30]`, each
containing the ordinate of a zero of zeta on the critical line).  Conclusion: every window of 622 (resp.
711) consecutive `n >= 1` has an `n` with `c n > 0` and an `n` with `c n < 0`; the `_runs` form says that no
window of 622 has all `c n >= 0` or all `c n <= 0`.
-/

open Complex Finset

namespace KeiperComb

noncomputable section

""")
out.append(d_zero + "\n" + d_li + "\n" + d_w + "\n" + d_zi + "\nend\nend KeiperComb\n\n")

def tier(n, chunks_prefix, asm):
    s = rd(asm)
    o = []
    for c in range(19):
        t = rd(f"{chunks_prefix}C{c:02d}.lean")
        m = re.search(r"^def nsC : List Nat := \[.*\]$", t, re.M)
        o.append(f"namespace KeiperComb.N{n}.C{c:02d}\n{m.group(0)}\nend KeiperComb.N{n}.C{c:02d}\n\n")
    o.append(f"namespace KeiperComb.N{n}\n\nopen Complex Finset\n\n")
    for pat in [r"^def NSall : List ℕ := .*$", r"^def N0 : ℕ := .*$", r"^def L0 : List ℕ := .*$",
                r"^def loQ .*$", r"^def hiQ .*$"]:
        o.append(re.search(pat, s, re.M).group(0) + "\n\n")
    return "".join(o), s

def thm(s, name):
    m = re.search(r"^theorem " + re.escape(name) + r" \{c.*?:=\n", s, re.M | re.S)
    t = m.group(0)
    t = t[:t.rindex(":=")] + ":= by\n  sorry\n"
    return t

t622, s622 = tier(622, "KeiperComb/Numerics622".replace("KeiperComb/", ""), "Numerics622Assembly.lean")
out.append(t622)
out.append(thm(s622, "theoremA'_622_numerics") + "\n" + thm(s622, "theoremA'_622_runs_numerics") + "\nend KeiperComb.N622\n\n")
t711, s711 = tier(711, "Numerics711", "Numerics711Assembly.lean")
out.append(t711)
out.append(thm(s711, "theoremA'_711_numerics") + "\nend KeiperComb.N711\n")
sys.stdout.write("".join(out))
