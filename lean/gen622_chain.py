#!/usr/bin/env python3
"""Writes KeiperComb/Numerics622Chain.lean (B3): chain_mem for M = 7, 8 chain vectors.
Reuses N711.P_bounds-style hypotheses (same zero 1, same P bounds) and the `leafc` macro of Numerics711Chain.
Run from this directory: python3 -I gen622_chain.py"""
import re
src = open("KeiperComb/Numerics622Cert.lean").read()
vecs = eval(re.search(r"def chainVecs : List \(List Nat\) := (.*)", src).group(1))
conds = ["(711:ℝ)/2 - 4*P", "(889:ℝ)/2 - 5*P", "(1067:ℝ)/2 - 6*P", "(1:ℝ)/2",
         "(179:ℝ)/2 - P", "(357:ℝ)/2 - 2*P", "(535:ℝ)/2 - 3*P"]
assert len(vecs) == len(conds) + 1
hyp = "(P u : ℝ) (hP1 : (1110601 : ℝ) / 12500 ≤ P) (hP2 : P ≤ (88848139 : ℝ) / 1000000)\n    (hu0 : 0 ≤ u) (hu1 : u < 1)"
out = ["import KeiperComb.Numerics711Chain\nimport KeiperComb.Numerics622Cert\n",
       "/-! B3 (generated by gen622_chain.py, do not edit): `cvec P u` is a chain vector, M = 7. -/\n",
       "open Complex Finset\nset_option maxHeartbeats 800000\nnamespace KeiperComb.N622\nopen KeiperComb.N711\n"]
for k, v in enumerate(vecs):
    ns = "".join(" (n%d : ¬ (u < %s))" % (i, conds[i]) for i in range(k))
    c = (" (c : u < %s)" % conds[k]) if k < len(conds) else ""
    out.append("lemma leaf%d %s%s%s :\n    ∀ j, j < 7 → cvec P u j = (((%s : List Nat).getD j 0 : ℤ)) := by\n  try push Not at *\n  leafc\n" % (k, hyp, ns, c, v))
out.append("theorem chain_mem %s :\n    ∃ r ∈ chainVecs, ∀ j, j < 7 → cvec P u j = (r.getD j 0 : ℤ) := by" % hyp)
for k, v in enumerate(vecs):
    ns = " ".join("n%d" % i for i in range(k))
    if k < len(conds):
        out.append("  by_cases c%d : u < %s\n  · exact ⟨%s, by decide, leaf%d P u hP1 hP2 hu0 hu1 %s c%d⟩" % (k, conds[k], v, k, ns, k))
        out.append("  have n%d := c%d" % (k, k)) if False else None
        out.append("  have n%d := c%d" % (k, k))
    else:
        out.append("  exact ⟨%s, by decide, leaf%d P u hP1 hP2 hu0 hu1 %s⟩" % (v, k, ns))
out.append("\nend KeiperComb.N622\n")
open("KeiperComb/Numerics622Chain.lean", "w").write("\n".join(x for x in out if x))
